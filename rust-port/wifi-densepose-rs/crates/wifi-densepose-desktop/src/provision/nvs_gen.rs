//! Native ESP-IDF NVS partition binary generator (no Python dependency).
//!
//! Implements the subset of the ESP-IDF NVS (Non-Volatile Storage) v2
//! "multipage" binary format needed to provision an ESP32 CSI node's
//! `csi_cfg` namespace with the WiFi/target keys the firmware reads in
//! `firmware/esp32-csi-node/main/nvs_config.c`.
//!
//! The output is a `0x6000`-byte (24 KiB) image, byte-for-byte identical to
//! what ESP-IDF's `esp_idf_nvs_partition_gen generate <csv> <bin> 0x6000`
//! produces for the same key set, so the operator no longer needs Python
//! installed to run the in-app provisioning flow. The
//! `tests/fixtures/nvs_csi_cfg_golden.bin` golden fixture (generated by that
//! tool) is asserted byte-for-byte by the unit tests below.
//!
//! ## Full-replace semantics (issue #391)
//!
//! Flashing this image to NVS offset `0x9000` REPLACES the entire `csi_cfg`
//! namespace — there is no merge with whatever is already on the device.
//! [`Esp32NvsConfig`] therefore requires the full WiFi trio so the wizard
//! path can never silently wipe credentials.
//!
//! ## Format reference (reverse-engineered from the golden fixture)
//!
//! * Partition = N × 4096-byte **pages**. We populate page 0 and leave the
//!   remaining pages `0xff`-filled (uninitialised), matching the generator.
//! * Page layout: 32-byte **header** + 32-byte **entry-state bitmap** +
//!   126 × 32-byte **entries**.
//! * Header: `state`(4, LE `0xfffffffe` = ACTIVE) + `seq_number`(4, LE) +
//!   `version`(1, `0xfe` = v2) + `unused`(19, `0xff`) + `crc32`(4, over
//!   bytes `[4..28]`).
//! * Bitmap: 2 bits per entry, LSB-first; `0b10` (=2) written, `0b11` (=3)
//!   empty. So a written entry contributes `0xaa`-style bytes.
//! * Entry (32 bytes): `NS`(1) + `Type`(1) + `Span`(1) + `ChunkIndex`(1) +
//!   `CRC32`(4, over the 28 bytes = header `[0..4]` ++ key ++ data) +
//!   `Key`(16, NUL-terminated, `0xff`-padded) + `Data`(8).
//! * Namespace entry: `NS=0`, `Type=U8(0x01)`, `Key="csi_cfg"`, data byte 0
//!   holds the namespace index (1); remaining 7 data bytes `0xff`.
//! * Primitive entry (U8/U16): `NS=<ns index>`, `Span=1`, `ChunkIndex=0xff`,
//!   data holds the little-endian value, remaining data bytes `0xff`.
//! * String entry: `NS=<ns index>`, `Type=STR(0x21)`, `Span=1+ceil(len/32)`,
//!   `ChunkIndex=0xff`, data = `size`(2, LE, = `strlen+1` incl NUL) +
//!   `reserved`(2, `0xffff`) + `crc32`(4, over the NUL-terminated body).
//!   The body follows in the next `Span-1` entry slots, `0xff`-padded.
//!
//! CRC32 here follows ESP-IDF's NVS convention (`zlib.crc32(data, 0xffffffff)`):
//! the standard reflected CRC-32/ISO-HDLC table algorithm with the running
//! register seeded at `0` and the usual final `^ 0xffffffff` applied. See
//! [`crc32_le`] and the golden test for the empirical grounding.

use serde::{Deserialize, Serialize};

use crate::domain::config::ProvisioningConfig;

/// Total NVS partition size we emit (24 KiB), matching the ESP-IDF standard
/// 4 MB partition table's `nvs` partition and provision.py's `NVS_PARTITION_SIZE`.
pub const NVS_PARTITION_SIZE: usize = 0x6000;

/// One NVS page is 4096 bytes.
const PAGE_SIZE: usize = 4096;

/// Each entry (and the page header, and each bitmap slot) is 32 bytes.
const ENTRY_SIZE: usize = 32;

/// The page header occupies the first 32-byte slot of a page.
const PAGE_HEADER_SIZE: usize = ENTRY_SIZE;

/// The entry-state bitmap occupies the second 32-byte slot (2 bits per entry
/// × 126 entries = 252 bits, rounded up to 32 bytes).
const BITMAP_SIZE: usize = ENTRY_SIZE;

/// Byte offset of the first entry within a page (after header + bitmap).
const ENTRIES_OFFSET: usize = PAGE_HEADER_SIZE + BITMAP_SIZE;

/// Entries per page after the header and bitmap slots.
const ENTRIES_PER_PAGE: usize = (PAGE_SIZE - ENTRIES_OFFSET) / ENTRY_SIZE;

/// NVS item type tags (subset).
const TYPE_U8: u8 = 0x01;
const TYPE_U16: u8 = 0x02;
const TYPE_STR: u8 = 0x21;

/// Namespace index assigned to `csi_cfg` (first and only namespace).
const NS_INDEX: u8 = 1;

/// Flash-default byte for unwritten regions.
const FF: u8 = 0xff;

/// Configuration for the `csi_cfg` NVS namespace.
///
/// The WiFi trio (`ssid`, `password`, `target_ip`) is mandatory: writing this
/// image is full-replace, so a partial config would erase credentials on the
/// device (issue #391). Optional keys map to the firmware defaults when absent.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Esp32NvsConfig {
    /// WiFi SSID (2.4 GHz network the node joins).
    pub ssid: String,
    /// WiFi password (may be empty for open networks, but must be provided).
    pub password: String,
    /// Aggregator/hub IP the node streams CSI to.
    pub target_ip: String,
    /// Aggregator UDP port (firmware default 5005).
    pub target_port: u16,
    /// Node identifier (0-255).
    pub node_id: u8,
    /// Optional TDM slot index for this node (0-based).
    pub tdm_slot: Option<u8>,
    /// Optional total node count in the TDM schedule.
    pub tdm_nodes: Option<u8>,
}

impl Esp32NvsConfig {
    /// Validate provisioning invariants before generating the image.
    ///
    /// * `target_port` must be non-zero.
    /// * `tdm_slot`/`tdm_nodes` must be supplied together and `slot < nodes`
    ///   (matches provision.py and the firmware's clamp warning).
    /// * String lengths must fit the firmware buffers (`nvs_config.h`).
    pub fn validate(&self) -> Result<(), String> {
        if self.ssid.is_empty() {
            return Err("ssid must not be empty".into());
        }
        if self.target_ip.is_empty() {
            return Err("target_ip must not be empty".into());
        }
        if self.target_port == 0 {
            return Err("target_port must be non-zero".into());
        }
        // Firmware buffers: SSID 33, password 65, IP 16 (incl NUL).
        if self.ssid.len() > 32 {
            return Err(format!("ssid too long ({} > 32 chars)", self.ssid.len()));
        }
        if self.password.len() > 64 {
            return Err(format!(
                "password too long ({} > 64 chars)",
                self.password.len()
            ));
        }
        if self.target_ip.len() > 15 {
            return Err(format!(
                "target_ip too long ({} > 15 chars)",
                self.target_ip.len()
            ));
        }
        match (self.tdm_slot, self.tdm_nodes) {
            (Some(_), None) | (None, Some(_)) => {
                return Err("tdm_slot and tdm_nodes must be set together".into());
            }
            (Some(slot), Some(nodes)) => {
                if nodes == 0 {
                    return Err("tdm_nodes must be >= 1".into());
                }
                if slot >= nodes {
                    return Err(format!(
                        "tdm_slot ({slot}) must be less than tdm_nodes ({nodes})"
                    ));
                }
            }
            (None, None) => {}
        }
        Ok(())
    }

    /// Build from the desktop's richer [`ProvisioningConfig`], mapping the
    /// subset the native generator writes. Errors if the WiFi trio is missing.
    pub fn from_provisioning(cfg: &ProvisioningConfig) -> Result<Self, String> {
        Ok(Self {
            ssid: cfg
                .wifi_ssid
                .clone()
                .ok_or("wifi_ssid is required for NVS provisioning")?,
            password: cfg.wifi_password.clone().unwrap_or_default(),
            target_ip: cfg
                .target_ip
                .clone()
                .ok_or("target_ip is required for NVS provisioning")?,
            target_port: cfg.target_port.unwrap_or(5005),
            node_id: cfg.node_id.unwrap_or(1),
            tdm_slot: cfg.tdm_slot,
            tdm_nodes: cfg.tdm_total,
        })
    }
}

/// A single logical NVS entry to be laid out on a page. String entries expand
/// into multiple 32-byte slots (header slot + body slots).
enum Item {
    Namespace,
    U8 { key: &'static str, value: u8 },
    U16 { key: &'static str, value: u16 },
    Str { key: &'static str, value: String },
}

/// Generate the `csi_cfg` NVS partition image for `cfg`.
///
/// Returns a [`NVS_PARTITION_SIZE`]-byte image ready to flash at offset
/// `0x9000`. The byte layout matches ESP-IDF's generator for the same keys
/// (see the golden test).
pub fn generate_nvs_csi_cfg(cfg: &Esp32NvsConfig) -> Result<Vec<u8>, String> {
    cfg.validate()?;

    // Assemble the logical items in the same order provision.py's
    // build_nvs_csv writes them (namespace first, then keys), which is the
    // order ESP-IDF lays entries out and thus what the golden fixture uses.
    let mut items: Vec<Item> = vec![
        Item::Namespace,
        Item::Str {
            key: "ssid",
            value: cfg.ssid.clone(),
        },
        Item::Str {
            key: "password",
            value: cfg.password.clone(),
        },
        Item::Str {
            key: "target_ip",
            value: cfg.target_ip.clone(),
        },
        Item::U16 {
            key: "target_port",
            value: cfg.target_port,
        },
        Item::U8 {
            key: "node_id",
            value: cfg.node_id,
        },
    ];
    if let (Some(slot), Some(nodes)) = (cfg.tdm_slot, cfg.tdm_nodes) {
        items.push(Item::U8 {
            key: "tdm_slot",
            value: slot,
        });
        items.push(Item::U8 {
            key: "tdm_nodes",
            value: nodes,
        });
    }

    // Render each item into its 32-byte entry slots.
    let mut entries: Vec<[u8; ENTRY_SIZE]> = Vec::new();
    for item in &items {
        render_item(item, &mut entries)?;
    }

    if entries.len() > ENTRIES_PER_PAGE {
        return Err(format!(
            "NVS config too large: {} entries exceed one page ({})",
            entries.len(),
            ENTRIES_PER_PAGE
        ));
    }

    let mut image = vec![FF; NVS_PARTITION_SIZE];
    write_page0(&mut image, &entries);
    Ok(image)
}

/// Render one logical item into one or more 32-byte entry slots.
fn render_item(item: &Item, out: &mut Vec<[u8; ENTRY_SIZE]>) -> Result<(), String> {
    match item {
        Item::Namespace => {
            // NS=0, Type=U8, key="csi_cfg", data[0]=namespace index.
            let mut data = [FF; 8];
            data[0] = NS_INDEX;
            out.push(build_entry(0, TYPE_U8, 1, 0xff, "csi_cfg", &data));
        }
        Item::U8 { key, value } => {
            let mut data = [FF; 8];
            data[0] = *value;
            out.push(build_entry(NS_INDEX, TYPE_U8, 1, 0xff, key, &data));
        }
        Item::U16 { key, value } => {
            let mut data = [FF; 8];
            data[0..2].copy_from_slice(&value.to_le_bytes());
            out.push(build_entry(NS_INDEX, TYPE_U16, 1, 0xff, key, &data));
        }
        Item::Str { key, value } => {
            // Body is the string plus a trailing NUL.
            let mut body = value.as_bytes().to_vec();
            body.push(0);
            let size = body.len();
            if size > u16::MAX as usize {
                return Err(format!("string '{key}' too long ({size} bytes)"));
            }
            let body_slots = size.div_ceil(ENTRY_SIZE);
            let span = 1 + body_slots as u8;

            // Header entry data: size(2) + reserved(2, 0xffff) + crc32(4, body).
            let mut data = [FF; 8];
            data[0..2].copy_from_slice(&(size as u16).to_le_bytes());
            // data[2..4] stay 0xff (reserved).
            let body_crc = crc32_le(&body);
            data[4..8].copy_from_slice(&body_crc.to_le_bytes());
            out.push(build_entry(NS_INDEX, TYPE_STR, span, 0xff, key, &data));

            // Body slots, 0xff-padded.
            for chunk in body.chunks(ENTRY_SIZE) {
                let mut slot = [FF; ENTRY_SIZE];
                slot[..chunk.len()].copy_from_slice(chunk);
                out.push(slot);
            }
        }
    }
    Ok(())
}

/// Build a 32-byte entry from its fields, computing the per-entry CRC32.
fn build_entry(
    ns: u8,
    item_type: u8,
    span: u8,
    chunk_index: u8,
    key: &str,
    data: &[u8; 8],
) -> [u8; ENTRY_SIZE] {
    let mut e = [FF; ENTRY_SIZE];
    e[0] = ns;
    e[1] = item_type;
    e[2] = span;
    e[3] = chunk_index;
    // e[4..8] = CRC, filled below.
    // Key: 16-byte field, NUL-terminated and **zero-padded** (verified against
    // the golden fixture — the padding is 0x00, not 0xff).
    e[8..24].fill(0);
    let kbytes = key.as_bytes();
    let klen = kbytes.len().min(15); // leave room for the NUL within 16
    e[8..8 + klen].copy_from_slice(&kbytes[..klen]);
    // e[8 + klen] stays 0 (NUL terminator); remaining key bytes stay 0.
    e[24..32].copy_from_slice(data);

    // CRC32 over header[0..4] ++ key[8..24] ++ data[24..32] (28 bytes),
    // i.e. everything except the CRC field itself.
    let mut crc_input = [0u8; 28];
    crc_input[0..4].copy_from_slice(&e[0..4]);
    crc_input[4..20].copy_from_slice(&e[8..24]);
    crc_input[20..28].copy_from_slice(&e[24..32]);
    let crc = crc32_le(&crc_input);
    e[4..8].copy_from_slice(&crc.to_le_bytes());
    e
}

/// Write page 0 (header + bitmap + entries) into the image. Remaining pages
/// stay `0xff` (uninitialised), matching the ESP-IDF generator.
fn write_page0(image: &mut [u8], entries: &[[u8; ENTRY_SIZE]]) {
    // --- Page header (bytes 0..32) ---
    // state = ACTIVE = 0xfffffffe (LE)
    image[0..4].copy_from_slice(&0xffff_fffe_u32.to_le_bytes());
    // seq_number = 0
    image[4..8].copy_from_slice(&0u32.to_le_bytes());
    // version = 0xfe (NVS format v2)
    image[8] = 0xfe;
    // unused bytes [9..28] stay 0xff.
    for b in image.iter_mut().take(28).skip(9) {
        *b = FF;
    }
    // header CRC over bytes [4..28]
    let hdr_crc = crc32_le(&image[4..28]);
    image[28..32].copy_from_slice(&hdr_crc.to_le_bytes());

    // --- Entry state bitmap (the slot after the header): 2 bits per entry,
    // LSB-first. written = 0b10 (2), empty = 0b11 (3). Start all-empty (0xff)
    // then mark each written entry.
    for b in image
        .iter_mut()
        .take(ENTRIES_OFFSET)
        .skip(PAGE_HEADER_SIZE)
    {
        *b = FF;
    }
    for (i, _) in entries.iter().enumerate() {
        let byte = PAGE_HEADER_SIZE + i / 4;
        let shift = (i % 4) * 2;
        // Clear the two bits (set to 0b00) then OR in 0b10 -> written(2).
        image[byte] &= !(0b11 << shift);
        image[byte] |= 0b10 << shift;
    }

    // --- Entries (after header + bitmap) ---
    for (i, entry) in entries.iter().enumerate() {
        let off = ENTRIES_OFFSET + i * ENTRY_SIZE;
        // All entries fit in one page by construction (checked by caller).
        image[off..off + ENTRY_SIZE].copy_from_slice(entry);
    }
}

