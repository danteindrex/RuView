/// ESP-IDF NVS entry CRC convention.
///
/// Empirically (verified against the ESP-IDF-generated golden fixture) this is
/// `zlib.crc32(data, 0xffffffff)`: the standard reflected CRC-32 table
/// algorithm with the running register **seeded at 0** and the usual final
/// `^ 0xffffffff` applied. (Seeding at 0 rather than `0xffffffff` is what the
/// `0xffffffff` continuation argument reduces to.)
fn crc32_le(data: &[u8]) -> u32 {
    let mut crc: u32 = 0x0000_0000;
    for &byte in data {
        let idx = ((crc ^ byte as u32) & 0xff) as usize;
        crc = (crc >> 8) ^ CRC32_TABLE[idx];
    }
    crc ^ 0xffff_ffff
}

