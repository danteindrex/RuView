    /// The compile-time table must be the canonical reflected CRC-32 table.
    #[test]
    fn crc32_table_is_canonical() {
        assert_eq!(CRC32_TABLE[0], 0x0000_0000);
        assert_eq!(CRC32_TABLE[1], 0x7707_3096);
        assert_eq!(CRC32_TABLE[255], 0x2d02_ef8d);
    }

    /// crc32_le must match ESP-IDF's NVS convention, i.e.
    /// `zlib.crc32(data, 0xffffffff)`. Reference values computed with Python
    /// zlib and verified byte-for-byte against the golden fixture.
    #[test]
    fn crc32_le_matches_nvs_convention() {
        // zlib.crc32(b"123456789", 0xffffffff) == 0xd202d277
        assert_eq!(crc32_le(b"123456789"), 0xd202_d277);
        // zlib.crc32(b"", 0xffffffff) == 0xffffffff
        assert_eq!(crc32_le(b""), 0xffff_ffff);
    }

    /// GOLDEN TEST: our generator must byte-for-byte reproduce ESP-IDF's
    /// output for the WiFi-trio + port + node_id fixture. This is the
    /// correctness proof for the whole NVS format implementation; it is
    /// hermetic (no Python, no network — the .bin is embedded).
    #[test]
    fn generate_matches_esp_idf_golden_byte_for_byte() {
        let golden: &[u8] = include_bytes!("../../tests/fixtures/nvs_csi_cfg_golden.bin");
        let ours = generate_nvs_csi_cfg(&golden_config()).expect("generation");

        assert_eq!(
            ours.len(),
            golden.len(),
            "image size mismatch: {} vs {}",
            ours.len(),
            golden.len()
        );

        if ours != golden {
            // Report the first divergence to make failures debuggable.
            let first = ours
                .iter()
                .zip(golden.iter())
                .position(|(a, b)| a != b)
                .unwrap();
            panic!(
                "NVS image diverges from golden at offset 0x{:x}: ours={:#04x} golden={:#04x}",
                first, ours[first], golden[first]
            );
        }
    }

